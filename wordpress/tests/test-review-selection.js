const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const element = (extra = {}) => ({ checked: false, dataset: {}, handlers: {}, addEventListener(name, fn) { this.handlers[name] = fn; }, ...extra });
const rows = Array.from({ length: 4 }, (_, i) => element({ dataset: { otje: i < 3 ? '1' : '0' } }));
const all = element(), count = {}, buttons = ['confirm', 'reject', 'otje'].map(value => ({ value }));
const form = element({ querySelectorAll: s => s.includes('observation_ids') ? rows : buttons, querySelector: s => s.includes('select-all') ? all : count });
const image = element({ dataset: { fallback: '/nest.webp' }, complete: true, naturalWidth: 0 });
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '../backyard/admin/review.js'), 'utf8'), { document: { querySelectorAll: s => s.includes('bulk-review') ? [form] : [image] }, window: element() });
assert.equal(buttons[0].disabled, true);
rows[0].checked = true; rows[0].handlers.click({ shiftKey: false });
rows[2].checked = true; rows[2].handlers.click({ shiftKey: true });
assert.deepEqual(rows.map(row => row.checked), [true, true, true, false]);
assert.equal(all.indeterminate, true); assert.equal(buttons[2].disabled, false);
all.checked = true; all.handlers.change();
assert.equal(rows.every(row => row.checked), true); assert.equal(buttons[2].disabled, true);
all.checked = false; all.handlers.change();
assert.equal(rows.some(row => row.checked), false); assert.equal(buttons[0].disabled, true);
assert.equal(image.src, '/nest.webp');
console.log('Shift-click, select-all, Otje gating and image fallback checks passed.');
